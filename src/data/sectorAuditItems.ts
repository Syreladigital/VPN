// Fonction d'export pour récupérer les items
// ========================================
export function getSectorItems(sector: string): Record<string, AuditItem[]> {
  switch (sector) {
    case 'sante_reglementee_pharmacien':
      return pharmacienItems;
    case 'sante_reglementee_medecin':
      return medecinItems;
    case 'sante_non_reglementee_bien_etre':
      return bienEtreItems;
    case 'assurance_vie':
      return assuranceVieItems;
    case 'assurance_non_vie':
      return assuranceNonVieItems;
    case 'transport_logistique':
      return transportItems;
    default:
      return {};
  }
}

export function getAuditItemsForModule(moduleId: string, sector: string, resetToNonConforme: boolean = true): AuditItem[] {
  const sectorData = getSectorItems(sector);
  const items = sectorData[moduleId] || [];
  
  // Par défaut, initialiser tous les items à non_conforme pour un score de 0%
  if (resetToNonConforme) {
    return items.map(item => ({
      ...item,
      status: 'non_conforme' as const,
      actions: item.actions.map(action => ({
        ...action,
        completed: false
      }))
    }));
  }
  
  return items;
}
